function pscSrc(s){
  if(!s) return '';
  const m = String(s).match(/^(第[一二三四五六]章)/);
  if(!m) return s;
  const t = PSC_BOOK2SITE[m[1]];
  if(!t) return s;
  return '原书' + m[1] + String(s).slice(m[1].length) + '　→　本站' + t.no + '「' + t.title + '」';
}

