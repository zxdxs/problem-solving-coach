TPL_HEAD = '''
  <h2 id="addendum" style="margin-top:38px">原书补遗</h2>
  <p class="muted">以下各条均出自原书{CH}一章，是本站此前未收的部分。
  出处一律写<b>章节名与表号，不写章号</b>——原书章内交叉引用的章号错乱已六次，照抄会出错。</p>
  <div class="table-scroll">
  <table>
    <thead><tr><th style="width:22%">条目</th><th style="width:60%">内容</th><th style="width:18%">出处</th></tr></thead>
    <tbody>
'''

TPL_ROW = '      <tr><td><b>{a}</b></td><td>{b}</td><td class="muted">{c}</td></tr>\n'

TPL_TAIL = '''    </tbody>
  </table>
  </div>
'''

for fname, (ch, rows) in D.items():
    p = fname + '.html'
    s = io.open(p, encoding='utf-8').read()
    if 'id="addendum"' in s:
        print('跳过（已存在）:', p); continue
    block = TPL_HEAD.replace('{CH}', ch)
    for a, b, c in rows:
        block += TPL_ROW.format(a=a, b=b, c=c)
    block += TPL_TAIL
    idx = s.find('  <div class="pager">')
    if idx < 0:
        print('!! 找不到 pager:', p); continue
    s = s[:idx] + block + '\n' + s[idx:]
    io.open(p, 'w', encoding='utf-8').write(s)
    print('已插入 %2d 条 → %s' % (len(rows), p))
